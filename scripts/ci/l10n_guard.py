#!/usr/bin/env python3
"""Localization heads-ups for a branch, from the diff between BASE and HEAD.

What a PR may edit comes from CONTRIBUTING.md and l10n.yaml:
- CONTRIBUTING.md: the translation files under the arb dir belong to Weblate,
  and new English strings go in the template arb (app_en.arb). So any other
  .arb there that changed is flagged.
- The generated localization files (output-localization-file and its
  per-language siblings) are regenerated by maintainers on main, so they
  are flagged as something to leave out. That one is practice, not a rule.
- In the template arb, a reworded English value and a new key with no
  description for translators get a heads-up. Editing the template is fine.
Anything else under the arb dir, such as hand-written Dart, is never flagged.

Advisory only, exits 0 whatever it finds.

Example: scripts/ci/l10n_guard.py upstream/main HEAD --out l10n.json
"""

import argparse
import json
import os
import posixpath
import re
import subprocess
import sys

sys.dont_write_bytecode = True  # no __pycache__ next to the scripts
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from touched_lines_diagnostics import git, repo_root  # noqa: E402

L10N_DEFAULTS = {
    'arb-dir': 'lib/l10n',
    'template-arb-file': 'app_en.arb',
    'output-localization-file': 'app_localizations.dart',
}


def l10n_config(root):
    """The three l10n.yaml keys this needs, from plain `key: value` lines."""
    config = dict(L10N_DEFAULTS)
    try:
        with open(os.path.join(root, 'l10n.yaml')) as f:
            for line in f:
                m = re.match(r'^([\w-]+)\s*:\s*(.+?)\s*$', line.split('#', 1)[0])
                if m and m.group(1) in config:
                    config[m.group(1)] = m.group(2).strip('\'"')
    except OSError:
        pass
    return config


def generated_names(output_file, template_name, arb_names):
    """app_localizations.dart plus one app_localizations_<lang>.dart per
    app_<lang>.arb, as flutter gen-l10n names them. Exact basenames, so
    hand-written files like current_app_localizations.dart never match."""
    stem, ext = posixpath.splitext(output_file)
    prefix = template_name.rsplit('_', 1)[0] + '_'
    names = {output_file}
    for arb in arb_names:
        if arb.startswith(prefix) and arb.endswith('.arb'):
            # app_en_GB.arb lands in app_localizations_en.dart.
            locale = arb[len(prefix):-4]
            names.update({f'{stem}_{locale}{ext}', f'{stem}_{locale.split("_")[0]}{ext}'})
    return names


def load_arb(text):
    try:
        data = json.loads(text)
    except ValueError:
        return None
    return data if isinstance(data, dict) else None


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('base', help='base ref, e.g. upstream/main or origin/main')
    parser.add_argument('head', nargs='?', default='HEAD', help='head ref (default HEAD)')
    parser.add_argument('--out', help='write the JSON result to this file')
    args = parser.parse_args()

    root = repo_root()
    config = l10n_config(root)
    arb_dir = config['arb-dir'].rstrip('/')
    template = posixpath.join(arb_dir, config['template-arb-file'])
    output_file = config['output-localization-file']

    changed = git('diff', '--name-only', '--no-renames', f'{args.base}...{args.head}', cwd=root).splitlines()
    arb_names = {posixpath.basename(p) for p in changed if p.endswith('.arb')}
    tree = git('ls-tree', '--name-only', args.head, arb_dir + '/', cwd=root)
    arb_names |= {posixpath.basename(p) for p in tree.splitlines()}
    generated = generated_names(output_file, config['template-arb-file'], arb_names)
    items = []

    def add(check, subject, message):
        items.append({'check': check, 'file_or_key': subject, 'message': message})

    translations, generated_changed = [], []
    for path in changed:
        if posixpath.dirname(path) != arb_dir:
            continue
        name = posixpath.basename(path)
        if name.endswith('.arb') and path != template:
            translations.append(path)
        elif name in generated:
            generated_changed.append(path)

    # A regenerated or bulk-edited set touches dozens of files, one line for
    # all of them reads better than dozens of identical ones.
    def files_subject(paths):
        return paths[0] if len(paths) == 1 else f'{paths[0]} and {len(paths) - 1} more'

    if translations:
        subject = files_subject(translations)
        add('translation-arb', subject,
            f'{subject}: Weblate owns the translation files and will overwrite this edit on its next sync. '
            f'Translations go through translate.moonfin.io, only {template} belongs in a PR.')
    if generated_changed:
        subject = files_subject(generated_changed)
        add('generated-dart', subject,
            f'{subject}: generated by flutter gen-l10n. Maintainers regenerate these on main, '
            f'so leave them out of the PR.')

    if template in changed:
        def read(ref):
            try:
                return git('show', f'{ref}:{template}', cwd=root)
            except subprocess.CalledProcessError:
                return '{}'
        merge_base = git('merge-base', args.base, args.head, cwd=root).strip()
        old, new = load_arb(read(merge_base)), load_arb(read(args.head))
        if new is None:
            add('invalid-arb', template, f'{template}: not valid JSON at {args.head}.')
        elif old is not None:
            for key, value in new.items():
                if key.startswith('@'):
                    continue
                if key in old:
                    if old[key] != value:
                        add('reworded', key,
                            f'{key}: the English text changed, so every translation of it goes stale. '
                            f'If the meaning changed, a new key may be better.')
                else:
                    meta = new.get('@' + key)
                    description = meta.get('description') if isinstance(meta, dict) else None
                    if not isinstance(description, str) or not description.strip():
                        add('no-description', key,
                            f'{key}: no description for translators. Add "@{key}": {{"description": ...}} '
                            f'saying where it shows up.')

    result = {'count': len(items), 'items': items}
    if args.out:
        with open(args.out, 'w') as f:
            json.dump(result, f, indent=2)

    print(f'{len(items)} localization findings since {args.base}')
    for item in items:
        print(f"  [{item['check']}] {item['message']}")


if __name__ == '__main__':
    try:
        main()
    except subprocess.CalledProcessError as e:
        sys.exit(f"error: {' '.join(e.cmd)} failed: {(e.stderr or '').strip()}")
